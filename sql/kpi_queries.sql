
-- ==========================================
-- OrderFlow360: KPI Queries
-- Run against the DuckDB warehouse
-- ==========================================


-- 1. Overall Order Summary
SELECT
    COUNT(*) AS TOTAL_ORDERS,
    COUNT(DISTINCT ORDER_ID) AS UNIQUE_ORDERS,
    ROUND(SUM(ORDER_VALUE), 2) AS TOTAL_ORDER_VALUE,
    ROUND(AVG(ORDER_VALUE), 2) AS AVERAGE_ORDER_VALUE
FROM FACT_ORDER_FULFILLMENT;


-- 2. Orders by Status
SELECT
    ORDER_STATUS,
    COUNT(*) AS TOTAL_ORDERS,
    ROUND(SUM(ORDER_VALUE), 2) AS TOTAL_ORDER_VALUE
FROM FACT_ORDER_FULFILLMENT
GROUP BY ORDER_STATUS
ORDER BY TOTAL_ORDERS DESC;


-- 3. Delivery SLA Performance
SELECT
    COUNT(*) AS DELIVERED_ORDERS,
    COUNT(*) FILTER (WHERE SLA_MET = TRUE) AS ON_TIME_ORDERS,
    COUNT(*) FILTER (WHERE SLA_MET = FALSE) AS LATE_ORDERS,
    ROUND(
        100.0 * COUNT(*) FILTER (WHERE SLA_MET = TRUE)
        / NULLIF(COUNT(*), 0),
        2
    ) AS ON_TIME_PERCENTAGE
FROM FACT_ORDER_FULFILLMENT
WHERE ORDER_STATUS = 'Delivered';


-- 4. Courier Performance
SELECT
    c.COURIER_NAME,
    COUNT(*) AS DELIVERED_ORDERS,
    COUNT(*) FILTER (WHERE f.SLA_MET = TRUE) AS ON_TIME_ORDERS,
    ROUND(
        100.0 * COUNT(*) FILTER (WHERE f.SLA_MET = TRUE)
        / NULLIF(COUNT(*), 0),
        2
    ) AS ON_TIME_PERCENTAGE
FROM FACT_ORDER_FULFILLMENT f
LEFT JOIN DIM_COURIER c
    ON f.COURIER_ID = c.COURIER_ID
WHERE f.ORDER_STATUS = 'Delivered'
GROUP BY c.COURIER_NAME
ORDER BY ON_TIME_PERCENTAGE DESC NULLS LAST;


-- 5. Monthly Order Trends
SELECT
    YEAR(ORDER_DATE_KEY) AS YEAR,
    MONTH(ORDER_DATE_KEY) AS MONTH,
    COUNT(*) AS TOTAL_ORDERS,
    ROUND(SUM(ORDER_VALUE), 2) AS REVENUE
FROM FACT_ORDER_FULFILLMENT
GROUP BY YEAR, MONTH
ORDER BY YEAR, MONTH;


-- 6. Top 10 Customers by Order Count
SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    COUNT(*) AS TOTAL_ORDERS,
    ROUND(SUM(f.ORDER_VALUE), 2) AS TOTAL_ORDER_VALUE
FROM FACT_ORDER_FULFILLMENT f
LEFT JOIN DIM_CUSTOMER c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID
GROUP BY c.CUSTOMER_ID, c.CUSTOMER_NAME
ORDER BY TOTAL_ORDERS DESC
LIMIT 10;


-- 7. Average Delivery Duration by Courier
SELECT
    c.COURIER_NAME,
    COUNT(*) AS DELIVERED_ORDERS,
    ROUND(AVG(f.DELIVERY_DURATION_DAYS), 2)
        AS AVG_DELIVERY_DAYS
FROM FACT_ORDER_FULFILLMENT f
LEFT JOIN DIM_COURIER c
    ON f.COURIER_ID = c.COURIER_ID
WHERE f.ORDER_STATUS = 'Delivered'
GROUP BY c.COURIER_NAME
ORDER BY AVG_DELIVERY_DAYS;


-- 8. Data Quality: Unmatched Customer or Courier
SELECT
    COUNT(*) AS UNMATCHED_ORDERS
FROM FACT_ORDER_FULFILLMENT
WHERE CUSTOMER_ID IS NULL
   OR COURIER_ID IS NULL;


-- 9. Revenue by Product Category
SELECT
    CATEGORY,
    COUNT(*) AS ORDER_LINES,
    SUM(QUANTITY) AS UNITS_SOLD,
    ROUND(SUM(ORDER_VALUE), 2) AS TOTAL_REVENUE
FROM FACT_ORDER_FULFILLMENT
GROUP BY CATEGORY
ORDER BY TOTAL_REVENUE DESC;
